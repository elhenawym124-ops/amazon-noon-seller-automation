const fs = require('fs');
const txt = fs.readFileSync('summaries/active_listings_10nov.txt', 'utf8');
const lines = txt.split(/\r?\n/).filter(Boolean);
const hdr = lines[0].replace(/^\uFEFF/, '').split('\t');
const idx = n => hdr.indexOf(n);
const iSku = idx('seller-sku'), iQty = idx('quantity'), iPrice = idx('price'), iStatus = idx('status'), iAsin = idx('asin1'), iOpen = idx('open-date');
const rows = lines.slice(1).map(l => l.split('\t')).filter(c => /^LVP-/.test(c[iSku] || ''));
console.log('our SKUs in report:', rows.length);
const byQty = {};
for (const c of rows) byQty[c[iQty]] = (byQty[c[iQty]] || 0) + 1;
console.log('quantity distribution:', JSON.stringify(byQty));
const byStatus = {};
for (const c of rows) byStatus[c[iStatus]] = (byStatus[c[iStatus]] || 0) + 1;
console.log('status distribution:', JSON.stringify(byStatus));
const noPrice = rows.filter(c => !parseFloat(c[iPrice]));
console.log('rows with price 0/empty:', noPrice.length, noPrice.slice(0, 5).map(c => c[iSku]).join(','));
const zeroQty = rows.filter(c => (c[iQty] || '0') === '0').map(c => c[iSku]);
console.log('zero qty:', zeroQty.length, zeroQty.slice(0, 20).join(','));
const newOnes = rows.filter(c => /LVP-(5\d\d)/.test(c[iSku]));
console.log('LVP-5xx present:', newOnes.length, newOnes.slice(0, 5).map(c => c[iSku] + ':' + c[iQty] + ':' + c[iPrice]).join(' | '));
